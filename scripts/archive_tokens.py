#!/usr/bin/env python3
"""Generate apps/web/src/lib/archive-tokens.css: the Lemmas hub's archive look (docs/SPEC.md §13.11).

Every stage gets light and dark tokens: the seven eras, nine night steps (proven large cardinals) and the
forced light/dark copies /dev/archive uses to show both side by side. Text colors are nudged until they pass
WCAG AA: ink and pencil 4.5:1 on the paper and on plates, gilt 3:1 (it marks large glyphs and rules).

Usage: python3 scripts/archive_tokens.py
"""

from __future__ import annotations

import re
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "apps/web/src/lib/archive-tokens.css"


def lum(h: str) -> float:
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (1, 3, 5))
    f = lambda c: c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)


def contrast(a: str, b: str) -> float:
    x, y = sorted((lum(a), lum(b)), reverse=True)
    return (x + 0.05) / (y + 0.05)


def mix(a: str, b: str, t: float) -> str:
    return "#" + "".join(f"{round(int(a[i:i + 2], 16) * (1 - t) + int(b[i:i + 2], 16) * t):02x}" for i in (1, 3, 5))


def fit(color: str, toward: str, bgs: list[str], need: float) -> str:
    """Move color toward `toward` until it passes `need` on every background."""
    for s in range(101):
        c = mix(color, toward, s / 100)
        if all(contrast(c, b) >= need for b in bgs):
            return c
    return toward


# paper, ink, pencil, rule, plate, gilt
ERAS = {
    # Parchment and terracotta, like a painted vase.
    "antiquity": (("#ead2a4", "#3b2312", "#6e4a2a", "#a0522d", "#e0c08a", "#8f3f16"),
                  ("#1d130b", "#f0dcb4", "#c9a576", "#b8653a", "#2a1c10", "#e39a5c")),
    # Illuminated manuscript: vellum, lapis and gold leaf.
    "golden-age": (("#f5ecd6", "#1c2240", "#4e4a6a", "#1f4e9c", "#e7dcbd", "#9a6c00"),
                   ("#0c1633", "#eae4cf", "#a9b3d6", "#4d7ad8", "#13214a", "#e8bd4a")),
    # Copperplate: warm grey paper, umber engraving.
    "renaissance": (("#e9e2d3", "#2a1d14", "#5e4c3c", "#5b3a22", "#ddd3be", "#7a4a1c"),
                    ("#1b1612", "#e9dfcf", "#b9a891", "#8a6545", "#261f19", "#d19a5c")),
    # Printed folio: crisp ivory, black type, red title-page accents.
    "enlightenment": (("#fbf8f1", "#111111", "#55524c", "#222222", "#f1ece1", "#a11d1d"),
                      ("#121212", "#f3efe6", "#aaa49a", "#8a8a8a", "#1c1c1c", "#ef6b5e")),
    # Lithograph and brass: sage paper, bottle green ink, brass rules.
    "steam-age": (("#e3e7d3", "#1d2b22", "#4a5a4c", "#8c6a1f", "#d6dcc2", "#7a5a12"),
                  ("#0f1d16", "#e4ecdf", "#a5b8a8", "#b8913a", "#16281f", "#e0b85a")),
    # Blueprint: drafting blue with white line work.
    "machine-age": (("#1f4a80", "#f3f8ff", "#c2d6f0", "#d8e7fb", "#275694", "#ffd76a"),
                    ("#0b1f3c", "#e8f1ff", "#9fbbe0", "#7fa6d8", "#11294d", "#ffcf5a")),
    # The present day: the site's own minimalist look.
    "space-age": (("#fafbfc", "#1c2330", "#5f6878", "#c3cad5", "#f0f3f7", "#3157c8"),
                  ("#12161d", "#e5e9f0", "#8b94a4", "#3a4352", "#171c24", "#86a5ff")),
}
NIGHT_END = ("#05060d", "#f1f3ff", "#a3abc9", "#4c5880", "#0d1124", "#ffe9a8")
# Light pages step past mid grey (where no ink passes AA) between the 4th and 5th large cardinal.
NIGHT_STEPS = (0.05, 0.1, 0.16, 0.23, 0.62, 0.71, 0.8, 0.9, 1.0)


def settle(t: tuple[str, ...]) -> tuple[str, ...]:
    paper, ink, pencil, rule, plate, gilt = t
    bgs = [paper, plate]
    if min(contrast(ink, b) for b in bgs) < 7:
        ink = max(("#141a26", "#f3f5ff"), key=lambda c: min(contrast(c, b) for b in bgs))
    return paper, ink, fit(pencil, ink, bgs, 4.6), rule, plate, fit(gilt, ink, bgs, 3.1)


def block(sel: str, t: tuple[str, ...]) -> str:
    p, i, pe, r, pl, g = t
    return f"{sel} {{ --paper: {p}; --ink-archive: {i}; --pencil: {pe}; --rule: {r}; --plate: {pl}; --gilt: {g}; }}"


def main() -> None:
    light, dark = [], []
    for era, (lt, dk) in ERAS.items():
        light.append(block(f'.archive[data-era="{era}"]', settle(lt)))
        dark.append(block(f'.archive[data-era="{era}"]', settle(dk)))
    for k, t in enumerate(NIGHT_STEPS, 1):
        light.append(block(f'.archive[data-night="{k}"]', settle(tuple(mix(a, b, t) for a, b in zip(ERAS["space-age"][0], NIGHT_END)))))
        dark.append(block(f'.archive[data-night="{k}"]', settle(tuple(mix(a, b, k / 9) for a, b in zip(ERAS["space-age"][1], NIGHT_END)))))
    out = [
        "/* The archive look (SPEC §13.11), hub only. Generated by scripts/archive_tokens.py: every stage, light and",
        "   dark; ink and pencil pass WCAG AA (4.5:1) on the paper and on plates, gilt 3:1. */",
        *light,
        "@media (prefers-color-scheme: dark) {",
        *("  " + d for d in dark),
        "}",
        "/* Forced schemes, for side-by-side previews (/dev/archive). */",
        *(l.replace(".archive", '.archive[data-scheme="light"]', 1) for l in light),
        *(d.replace(".archive", '.archive[data-scheme="dark"]', 1) for d in dark),
    ]
    bad = []
    for line in out:
        d = dict(re.findall(r"--(\S+): (#[0-9a-f]{6});", line))
        for lab, need in (("ink-archive", 4.5), ("pencil", 4.5), ("gilt", 3)):
            for bg in ("paper", "plate"):
                if d and contrast(d[lab], d[bg]) < need:
                    bad.append(f"{line[:50]} {lab} on {bg}: {contrast(d[lab], d[bg]):.2f}")
    if bad:
        raise SystemExit("\n".join(bad))
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT.relative_to(OUT.parents[4])}: {len(light)} stages, light and dark, all AA")


if __name__ == "__main__":
    main()
