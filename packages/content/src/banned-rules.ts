/**
 * Write content/banned-words.txt into firestore.rules (SPEC §13.2), between the BANNED-WORDS markers,
 * using the same pattern as the app (src/moderation.ts).
 *   pnpm moderation
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { bannedPattern } from "./moderation.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const words = readFileSync(join(root, "content/banned-words.txt"), "utf8")
  .split("\n")
  .map((l) => l.trim().toLowerCase())
  .filter((l) => l && !l.startsWith("#"));
for (const w of words) if (!/^[a-z][a-z ]*$/.test(w)) throw new Error(`Banned word "${w}": use lowercase letters and spaces only.`);

const pattern = bannedPattern(words);
if (/[\\']/.test(pattern)) throw new Error("The pattern must not contain backslashes or quotes.");
const block = [
  "    // BANNED-WORDS:START (generated by packages/content/src/banned-rules.ts from content/banned-words.txt)",
  `    function clean(s) { return !s.lower().matches('(?s).*${pattern}.*'); }`,
  "    // BANNED-WORDS:END",
].join("\n");

const path = join(root, "firestore.rules");
const rules = readFileSync(path, "utf8");
if (!rules.includes("BANNED-WORDS:START")) throw new Error("firestore.rules has no BANNED-WORDS markers.");
writeFileSync(path, rules.replace(/ *\/\/ BANNED-WORDS:START[\s\S]*?\/\/ BANNED-WORDS:END/, block));
console.log(`firestore.rules: ${words.length} banned words`);
