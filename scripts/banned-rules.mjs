// Write content/banned-words.txt into firestore.rules (SPEC §13.2), between the BANNED-WORDS markers.
//   pnpm moderation
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const words = readFileSync(join(root, "content/banned-words.txt"), "utf8")
  .split("\n")
  .map((l) => l.trim().toLowerCase())
  .filter((l) => l && !l.startsWith("#"));
for (const w of words) if (!/^[a-z][a-z ]*$/.test(w)) throw new Error(`Banned word "${w}": use lowercase letters and spaces only.`);

// Rules strings escape backslashes, so "\\b" in the file is the regex word boundary \b.
const re = `(?s).*\\\\b(${words.join("|")})(s|es|ed|ing)?\\\\b.*`;
const block = [
  "    // BANNED-WORDS:START (generated by scripts/banned-rules.mjs from content/banned-words.txt)",
  `    function clean(s) { return !s.lower().matches('${re}'); }`,
  "    // BANNED-WORDS:END",
].join("\n");

const path = join(root, "firestore.rules");
const rules = readFileSync(path, "utf8");
const next = rules.replace(/ *\/\/ BANNED-WORDS:START[\s\S]*?\/\/ BANNED-WORDS:END/, block);
if (next === rules && !rules.includes("BANNED-WORDS:START")) throw new Error("firestore.rules has no BANNED-WORDS markers.");
writeFileSync(path, next);
console.log(`firestore.rules: ${words.length} banned words`);
